"""Zips each generated pack (flat) and writes index.json for the app.

usage: build_index.py PACKS_DIR OUT_DIR [--release TAG]
       build_index.py --check        (licences of the catalogues only)
PACKS_DIR holds one folder per pack (pack.json + FLAC files); OUT_DIR gets <id>.zip and index.json.
Each entry carries the pack's version (the app offers an update when it rises) and the release
that hosts its zip (the catalogue index lives on another, fixed release).

Licences: only CC0, CC-BY and public domain recordings are published (the repository and the
packs are public; NC, Sampling+ or a licence without a name stop the build before any zip).
Recipes: a pack marked "recipes" in libraries.json / instruments.json lists in its entry the
sounds (recipeSounds, the <slug> of <kind>_<slug>_<n>.flac) or the parts (recipeParts, name to
keys) a style recipe may name as lib:<pack>:<sound>.
"""
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIBRARIES = HERE / 'libraries.json'
INSTRUMENTS = HERE / 'instruments.json'
# Normalised: upper case, spaces and underscores as dashes.
_ALLOWED = re.compile(r'^(CC0(-1\.0)?|CC-BY(-[1-4]\.0)?|PUBLIC-DOMAIN)$')


def licence_ok(name):
    """True for CC0, CC-BY (any version) and public domain; NC, SA, ND, Sampling+, blank: false."""
    if not isinstance(name, str):
        return False
    return bool(_ALLOWED.match(re.sub(r'[\s_]+', '-', name.strip()).upper()))


def check_catalogues(libraries=LIBRARIES, instruments=INSTRUMENTS):
    """Every source has a whitelisted licence and every pack or instrument names known sources."""
    errors = []
    for path, items, key in ((libraries, 'packs', 'sources'), (instruments, 'instruments', 'source')):
        data = json.loads(Path(path).read_text())
        ids = set()
        for s in data['sources']:
            ids.add(s['id'])
            if not licence_ok(s.get('licence')):
                errors.append(f"{Path(path).name}: source {s['id']}: licence {s.get('licence')!r} not allowed")
        for item in data[items]:
            named = item[key] if isinstance(item[key], list) else [item[key]]
            errors += [f"{Path(path).name}: {item['id']}: unknown source {n}" for n in named if n not in ids]
    if errors:
        raise SystemExit('\n'.join(errors))


def recipe_sources(libraries=LIBRARIES, instruments=INSTRUMENTS):
    """The packs open to recipes: library pack -> its rules' slugs, instrument -> {part: keys}."""
    out = {}
    for p in json.loads(Path(libraries).read_text())['packs']:
        if p.get('recipes'):
            out[p['id']] = list(dict.fromkeys(r['slug'] for r in p['rules']))
    for i in json.loads(Path(instruments).read_text())['instruments']:
        if i.get('recipes'):
            out[i['id']] = dict(i['recipes'])
    return out


def check_credits(d, manifest):
    """A pack built from a library carries its credits; each one must be whitelisted."""
    if 'credits' not in manifest:
        return  # generated by the model (generate_pack.py): no third-party recording
    bad = [c.get('licence') for c in manifest['credits'] if not licence_ok(c.get('licence'))]
    if not manifest['credits'] or bad:
        raise SystemExit(f'{d.name}: credits {bad or "empty"}: only CC0, CC-BY and public domain are published')


def recipe_fields(manifest, open_to_recipes):
    entry = open_to_recipes.get(manifest['id'])
    if entry is None:
        return {}
    if isinstance(entry, dict):
        return {'recipeParts': entry}
    slugs = {m.group(1) for s in manifest['sounds'] if (m := re.match(r'^[a-z0-9]+_([a-z0-9_]+?)_\d+\.flac$', s['file']))}
    return {'recipeSounds': sorted(slugs)}


def build(packs, out, release=None):
    packs, out = Path(packs), Path(out)
    check_catalogues()
    open_to_recipes = recipe_sources()
    dirs = sorted(p for p in packs.iterdir() if (p / 'pack.json').is_file())
    manifests = [(d, json.loads((d / 'pack.json').read_text())) for d in dirs]
    for d, manifest in manifests:  # all checked before anything is written
        check_credits(d, manifest)
    out.mkdir(parents=True, exist_ok=True)
    entries = []
    for d, manifest in manifests:
        if not manifest['sounds']:
            print(f'{d.name}: empty, left out')
            continue
        zip_path = out / f"{manifest['id']}.zip"
        with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_STORED) as z:  # FLAC is already compressed
            # A multizone instrument (instrument_pack.py) also carries its zones' recordings.
            zones = [z['file'] for z in manifest.get('instrument', {}).get('zones', [])]
            for f in dict.fromkeys(['pack.json'] + [s['file'] for s in manifest['sounds']] + zones):
                info = zipfile.ZipInfo(f, date_time=(2026, 1, 1, 0, 0, 0))
                z.writestr(info, (d / f).read_bytes())
        data = zip_path.read_bytes()
        # An instrument's preview is also published on its own: heard before the pack is downloaded.
        preview = {}
        if manifest.get('instrument') and (d / 'apercu.flac').is_file():
            name = f"{manifest['id']}-apercu.flac"
            bytes_ = (d / 'apercu.flac').read_bytes()
            (out / name).write_bytes(bytes_)
            preview = {'preview': name, 'previewSha256': hashlib.sha256(bytes_).hexdigest(), 'previewBytes': len(bytes_)}
        entries.append({
            'id': manifest['id'], 'name': manifest['name'], 'file': zip_path.name,
            'sha256': hashlib.sha256(data).hexdigest(), 'sizeBytes': len(data), 'sounds': len(manifest['sounds']),
            'version': manifest.get('version', 1), 'family': manifest.get('family', ''),
            **({'release': release} if release else {}), **preview, **recipe_fields(manifest, open_to_recipes),
        })
        print(f"{manifest['id']}: {len(manifest['sounds'])} sounds, {len(data) / 1e6:.1f} MB")
    (out / 'index.json').write_text(json.dumps({'packs': entries}, ensure_ascii=False, indent=1))
    index = (out / 'index.json').read_bytes()
    print(f'index.json sha256 {hashlib.sha256(index).hexdigest()} size {len(index)}')


def main():
    if sys.argv[1:] == ['--check']:
        check_catalogues()
        print('catalogues: licences and sources ok')
        return
    release = sys.argv[sys.argv.index('--release') + 1] if '--release' in sys.argv else None
    build(sys.argv[1], sys.argv[2], release)


if __name__ == '__main__':
    main()
