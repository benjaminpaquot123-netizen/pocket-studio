/** Tour 6, N2: each « À toi » says what to do (techno « À toi : le rim décalé… » had no verb). */
class Tour6TutoYourTurnTest {
    private val steps: List<Triple<String, TutoStep, TutoLevel>> = TutoCourse.STYLES.flatMap { style ->
        TutoLevel.entries.flatMap { level -> TutoCourse.of(style)!!.chaptersFor(level).flatMap { it.steps }.map { Triple(style, it, level) } }
    }

    private fun report(what: String, bad: List<String>) = assertTrue("${bad.size} $what:\n" + bad.joinToString("\n"), bad.isEmpty())

    /** N2: « À toi : le rim décalé, la petite accroche… » (techno, Pro): no verb, nothing to do. */
    @Test
    fun everyYourTurnSaysWhatToDo() {
        val bad = steps.filter { (_, s, l) -> "À toi" in s.textFor(l) && Tour6TutoWords.actions(s.textFor(l).substringAfter("À toi").trimStart(' ', ':')).isEmpty() }
            .map { (st, s, l) -> "$st/${s.id}/${l.code}" }.distinct()
        report("« À toi » without an action", bad - PENDING_VERB)
        assertTrue("done already, take out of PENDING_VERB: ${PENDING_VERB - bad.toSet()}", (PENDING_VERB - bad.toSet()).isEmpty())
    }

