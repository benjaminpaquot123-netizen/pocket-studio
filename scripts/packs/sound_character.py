#!/usr/bin/env python3
"""Files every drum and bass sound of the published packs by its measured character.

The sound browser's second level inside a style family (Benjamin's list n° 14): « Gros et grave »,
« Sec et court », « Saturé »… measured on the sound itself (rank_sounds.features: length, spectral
centroid, flatness, clear note), not guessed from its name.

Usage: sound_character.py <dir with one x_<pack id>/ folder per unzipped pack | features.json> <output .kt>
(features.json: {pack: {"family": …, "sounds": {file: {"kind": …, "f": features}}}}, as kept by a
previous run, so the packs need not be downloaded again.)
"""
import json
import sys
from pathlib import Path

import rank_sounds as rs

# One letter per character in the generated table; the labels are the app's (French keys, translated).
LABELS = {
    "s": "Sec et court",
    "g": "Long et grave",
    "p": "Rond et punchy",
    "d": "Saturé",
    "a": "Long et ample",
    "b": "Brillant",
    "m": "Mat",
    "e": "Équilibré",
    "o": "Doux et sombre",
    "n": "Avec une note",
    "l": "Grave",
    "h": "Aigu",
    "r": "Grave et rond",
}

# Families whose second level is something else (the machine, the library's own groups).
SKIP_FAMILIES = {"Machines", "Bruitages", "Acoustique", "Instruments"}


def character(kind, f):
    """The letter of a sound's character, or None for a kind not filed this way."""
    length, centroid, flat = f["length"], f["centroid"], f["flatness"]
    if kind == "kick":
        if flat >= 0.05:
            return "d"
        if length >= 0.38:
            return "g"
        if length <= 0.2:
            return "s"
        return "p"
    if kind in ("snare", "clap"):
        if length <= 0.18:
            return "s"
        if length >= 0.38:
            return "a"
        if centroid >= (2000 if kind == "snare" else 2200):
            return "b"
        if centroid <= (900 if kind == "snare" else 1600):
            return "m"
        return "e"
    if kind in ("hat", "open_hat"):
        if kind == "hat" and length <= 0.09:
            return "s"
        if centroid >= 8500:
            return "b"
        if centroid <= 5500:
            return "o"
        return "e"
    if kind == "perc":
        if f["pitch_clarity"] >= 0.6:
            return "n"
        if centroid <= 1500:
            return "l"
        if centroid >= 6000:
            return "h"
        return "e"
    if kind in ("bass", "808"):
        if flat >= 0.06:
            return "d"
        if centroid <= 70:
            return "r"
        if centroid >= 200:
            return "b"
        return "e"
    return None


def measured(root):
    root = Path(root)
    if root.suffix == ".json":
        return json.loads(root.read_text())
    out = {}
    for pack_dir in sorted(root.glob("x_*")):
        manifest = next(pack_dir.glob("*.json"), None)
        if manifest is None:
            continue
        meta = json.loads(manifest.read_text())
        sounds = {}
        for s in meta["sounds"]:
            path = pack_dir / s["file"]
            if path.exists():
                x, rate = rs.mono(path)
                sounds[s["file"]] = {"kind": s["kind"], "f": rs.features(x, rate)}
        out[meta["id"]] = {"family": meta.get("family", ""), "sounds": sounds}
    return out


def main(root, out):
    data = measured(root)
    lines = [
        "package com.pocketstudio.model",
        "",
        "/**",
        " * The measured character of each drum and bass sound of the style packs (generated by",
        " * scripts/packs/sound_character.py from the published packs): the sound browser's second level",
        " * inside a style family. Per pack: « file=letter » pairs, the file's « .flac » left out.",
        " */",
        "object SoundCharacter {",
        "    val LABELS: Map<Char, String> = mapOf(",
    ]
    lines += [f'        \'{k}\' to "{v}",' for k, v in LABELS.items()]
    lines += ["    )", "", "    private val TABLE: Map<String, String> = mapOf("]
    counts = {}
    for pack, p in sorted(data.items()):
        if p.get("family") in SKIP_FAMILIES:
            continue
        pairs = []
        for file, s in sorted(p["sounds"].items()):
            if not s.get("f"):
                continue
            c = character(s["kind"], s["f"])
            if c is None:
                continue
            counts[(s["kind"], c)] = counts.get((s["kind"], c), 0) + 1
            pairs.append(f"{file.removesuffix('.flac')}={c}")
        if pairs:
            lines.append(f'        "{pack}" to "{" ".join(pairs)}",')
    lines += [
        "    )",
        "",
        "    private val parsed = HashMap<String, Map<String, Char>>()",
        "",
        "    /** The character of [file] in [pack] (« Sec et court »…), or null when not measured. */",
        "    fun of(pack: String, file: String): String? {",
        "        val table = synchronized(parsed) {",
        "            parsed.getOrPut(pack) {",
        "                TABLE[pack].orEmpty().split(' ').filter { '=' in it }",
        "                    .associate { it.substringBefore('=') to it.substringAfter('=').first() }",
        "            }",
        "        }",
        "        return table[file.removeSuffix(\".flac\")]?.let(LABELS::get)",
        "    }",
        "}",
        "",
    ]
    Path(out).write_text("\n".join(lines))
    for (kind, c), n in sorted(counts.items()):
        print(f"  {kind:9s} {LABELS[c]:16s} {n}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
