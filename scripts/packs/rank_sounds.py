#!/usr/bin/env python3
"""Ranks the sounds of every downloaded pack, best first, for each kind of sound.

The packs are generated by a model: some takes are excellent, some are weak (late start, too
quiet, a kick without low end, a hat that rings for a second, a bass with no clear note). This
measures each one-shot and orders them so that the first sound the app proposes is a good one.

Usage: rank_sounds.py <dir with one x_<pack id>/ folder per unzipped pack> <output .kt file>
"""
import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf


def mono(path):
    data, rate = sf.read(path, always_2d=True, dtype="float32")
    return data.mean(axis=1), rate


def db(x):
    return 20 * np.log10(max(float(x), 1e-9))


def features(x, rate):
    peak = float(np.max(np.abs(x))) if len(x) else 0.0
    if peak <= 1e-6:
        return None
    env = np.abs(x)
    # Start: first sample above -40 dB of the peak; end: last one above -50 dB.
    above = np.nonzero(env > peak * 0.01)[0]
    tail = np.nonzero(env > peak * 0.003)[0]
    start = above[0] / rate
    end = tail[-1] / rate
    attack = (np.argmax(env) - above[0]) / rate
    body = x[above[0]:tail[-1] + 1]
    spectrum = np.abs(np.fft.rfft(body * np.hanning(len(body)))) + 1e-12
    freqs = np.fft.rfftfreq(len(body), 1 / rate)
    power = spectrum ** 2
    centroid = float((freqs * power).sum() / power.sum())
    low = float(power[freqs < 120].sum() / power.sum())
    flatness = float(np.exp(np.mean(np.log(spectrum))) / np.mean(spectrum))
    rms = float(np.sqrt(np.mean(body ** 2)))
    clipped = float(np.mean(np.abs(x) > 0.995))
    return {
        "peak_db": db(peak), "rms_db": db(rms), "start": start, "length": end - start, "attack": attack,
        "centroid": centroid, "low": low, "flatness": flatness, "clipped": clipped,
        "pitch_clarity": pitch_clarity(body, rate),
    }


def pitch_clarity(x, rate):
    """How clearly the sound has one note: the best normalised autocorrelation peak, 40 Hz to 1 kHz."""
    seg = x[: min(len(x), rate // 2)]
    if len(seg) < rate // 20:
        return 0.0
    seg = seg - seg.mean()
    ac = np.correlate(seg, seg, mode="full")[len(seg) - 1:]
    if ac[0] <= 0:
        return 0.0
    ac = ac / ac[0]
    lo, hi = rate // 1000, rate // 40
    return float(np.max(ac[lo:hi])) if hi > lo else 0.0


def in_range(v, lo, hi, soft):
    """1 inside [lo, hi], falling to 0 at `soft` beyond either end."""
    if lo <= v <= hi:
        return 1.0
    d = lo - v if v < lo else v - hi
    return max(0.0, 1.0 - d / soft)


def score(kind, f):
    s = 0.0
    # Every one-shot: starts at once, loud enough, not crushed.
    s += 2.0 * in_range(f["start"], 0, 0.004, 0.03)
    s += 1.0 * in_range(f["peak_db"], -6, 0, 12)
    s -= 4.0 * min(1.0, f["clipped"] * 200)
    if kind == "kick":
        s += 3.0 * in_range(f["low"], 0.45, 1.0, 0.35)
        s += 2.0 * in_range(f["attack"], 0, 0.012, 0.04)
        s += 2.0 * in_range(f["length"], 0.15, 0.7, 0.5)
        s += 1.0 * in_range(f["flatness"], 0, 0.15, 0.3)
    elif kind in ("snare", "clap"):
        s += 2.0 * in_range(f["attack"], 0, 0.015, 0.05)
        s += 2.0 * in_range(f["length"], 0.08, 0.45, 0.4)
        s += 1.5 * in_range(f["centroid"], 1200, 6000, 3000)
        s += 1.0 * in_range(f["low"], 0, 0.25, 0.3)
    elif kind == "hat":
        s += 3.0 * in_range(f["length"], 0.02, 0.15, 0.25)
        s += 2.0 * in_range(f["centroid"], 5000, 14000, 4000)
        s += 1.0 * in_range(f["low"], 0, 0.05, 0.2)
    elif kind == "open_hat":
        s += 2.0 * in_range(f["length"], 0.18, 0.8, 0.5)
        s += 2.0 * in_range(f["centroid"], 4500, 14000, 4000)
        s += 1.0 * in_range(f["low"], 0, 0.05, 0.2)
    elif kind in ("perc", "tom"):
        s += 2.0 * in_range(f["attack"], 0, 0.015, 0.05)
        s += 2.0 * in_range(f["length"], 0.04, 0.5, 0.5)
    elif kind == "808":
        s += 3.0 * in_range(f["pitch_clarity"], 0.85, 1.0, 0.4)
        s += 2.0 * in_range(f["low"], 0.5, 1.0, 0.4)
        s += 2.0 * in_range(f["length"], 0.6, 2.0, 0.6)
    elif kind == "bass":
        s += 3.0 * in_range(f["pitch_clarity"], 0.8, 1.0, 0.4)
        s += 1.5 * in_range(f["low"], 0.25, 1.0, 0.3)
        s += 1.0 * in_range(f["length"], 0.2, 1.5, 0.5)
    elif kind in ("stab", "pluck", "keys"):
        s += 2.5 * in_range(f["pitch_clarity"], 0.6, 1.0, 0.4)
        s += 2.0 * in_range(f["attack"], 0, 0.03, 0.1)
        s += 1.0 * in_range(f["flatness"], 0, 0.2, 0.3)
    elif kind in ("pad", "lead"):
        s += 2.5 * in_range(f["pitch_clarity"], 0.6, 1.0, 0.4)
        s += 1.5 * in_range(f["length"], 0.6, 4.0, 1.0)
        s += 1.0 * in_range(f["flatness"], 0, 0.2, 0.3)
    else:  # vocal, fx, loop: only the generic checks
        s += 1.0 * in_range(f["length"], 0.1, 4.0, 1.0)
    return round(s, 3)


def main(root, out):
    picks = {}
    report = []
    for pack_dir in sorted(Path(root).glob("x_*")):
        manifest = next(pack_dir.glob("*.json"), None)
        if manifest is None:
            continue
        meta = json.loads(manifest.read_text())
        by_kind = {}
        for sound in meta["sounds"]:
            path = pack_dir / sound["file"]
            if not path.exists():
                continue
            x, rate = mono(path)
            f = features(x, rate)
            value = -99.0 if f is None else score(sound["kind"], f)
            by_kind.setdefault(sound["kind"], []).append((value, sound["file"]))
            report.append((meta["id"], sound["kind"], sound["file"], value, f))
        picks[meta["id"]] = {k: [name for _, name in sorted(v, key=lambda t: (-t[0], t[1]))] for k, v in by_kind.items()}
    lines = [
        "package com.pocketstudio.model",
        "",
        "/**",
        " * The sounds of each pack in order of quality, best first, for each kind (generated by",
        " * scripts/packs/rank_sounds.py from the published packs: clean start, right length, low end of",
        " * a kick, brightness of a hat, clear note of a bass…). Sounds not listed keep their order after.",
        " */",
        "object PackPicks {",
        "    val ORDER: Map<String, Map<String, List<String>>> = mapOf(",
    ]
    for pack, kinds in sorted(picks.items()):
        lines.append(f'        "{pack}" to mapOf(')
        for kind, files in sorted(kinds.items()):
            names = ", ".join(f'"{n}"' for n in files)
            lines.append(f'            "{kind}" to listOf({names}),')
        lines.append("        ),")
    lines += [
        "    )",
        "",
        "    /** [sounds] of [pack] best first (unranked ones keep their order, after the ranked). */",
        "    fun <T> sorted(pack: String, kind: String, sounds: List<T>, file: (T) -> String): List<T> {",
        "        val order = ORDER[pack]?.get(kind) ?: return sounds",
        "        return sounds.sortedBy { order.indexOf(file(it)).let { i -> if (i < 0) Int.MAX_VALUE else i } }",
        "    }",
        "}",
        "",
    ]
    Path(out).write_text("\n".join(lines))
    worst = sorted((r for r in report if r[4] is not None), key=lambda r: r[3])[:12]
    print(f"{len(report)} sounds ranked in {len(picks)} packs")
    for pack, kind, name, value, f in worst:
        print(f"  low: {pack}/{name} ({kind}) score {value} start {f['start']:.3f}s len {f['length']:.2f}s peak {f['peak_db']:.1f} dB")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
