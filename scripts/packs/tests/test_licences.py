"""Licence whitelist: a pack or a source under a licence that is not CC0 / CC-BY / public domain
breaks the build (NC, Sampling+, a licence without a name)."""
import json
import tempfile
import unittest
from pathlib import Path

from helpers import PACKS_DIR, fake_pack

import build_index

CC0 = {'title': 't', 'author': 'a', 'licence': 'CC0-1.0', 'page': 'https://example.org'}


class LicenceWhitelist(unittest.TestCase):
    def test_accepted(self):
        for name in ('CC0-1.0', 'CC-BY-4.0', 'CC-BY-3.0', 'Public domain', 'cc0-1.0', 'CC BY 4.0'):
            self.assertTrue(build_index.licence_ok(name), name)

    def test_refused(self):
        for name in ('CC-BY-NC-4.0', 'CC BY-NC 3.0', 'CC-BY-NC-SA-4.0', 'Sampling+', 'Sampling Plus 1.0',
                     '', None, '   ', 'Unknown', 'CC-BY-SA-4.0', 'All rights reserved'):
            self.assertFalse(build_index.licence_ok(name), repr(name))

    def test_catalogues_of_the_repo_pass(self):
        build_index.check_catalogues(PACKS_DIR / 'libraries.json', PACKS_DIR / 'instruments.json')

    def test_catalogue_with_a_nc_source_is_refused(self):
        lib = json.loads((PACKS_DIR / 'libraries.json').read_text())
        lib['sources'].append({'id': 'bad', 'type': 'zip', 'title': 'x', 'author': 'y',
                               'licence': 'CC-BY-NC-4.0', 'page': 'https://example.org', 'url': 'https://example.org/x.zip'})
        with tempfile.TemporaryDirectory() as t:
            p = Path(t) / 'libraries.json'
            p.write_text(json.dumps(lib))
            with self.assertRaises(SystemExit) as e:
                build_index.check_catalogues(p, PACKS_DIR / 'instruments.json')
            self.assertIn('bad', str(e.exception))

    def test_catalogue_with_an_unnamed_licence_is_refused(self):
        inst = json.loads((PACKS_DIR / 'instruments.json').read_text())
        del inst['sources'][0]['licence']
        with tempfile.TemporaryDirectory() as t:
            p = Path(t) / 'instruments.json'
            p.write_text(json.dumps(inst))
            with self.assertRaises(SystemExit):
                build_index.check_catalogues(PACKS_DIR / 'libraries.json', p)

    def test_build_breaks_on_a_nc_pack(self):
        with tempfile.TemporaryDirectory() as t:
            fake_pack(Path(t) / 'packs', 'ok_pack', ['perc_shaker_01.flac'], credits=[CC0])
            fake_pack(Path(t) / 'packs', 'nc_pack', ['perc_x_01.flac'], credits=[{**CC0, 'licence': 'CC-BY-NC-3.0'}])
            with self.assertRaises(SystemExit) as e:
                build_index.build(Path(t) / 'packs', Path(t) / 'dist')
            self.assertIn('nc_pack', str(e.exception))
            self.assertFalse((Path(t) / 'dist' / 'index.json').exists())

    def test_build_breaks_on_sampling_plus_and_empty_credits(self):
        for credits in ([{**CC0, 'licence': 'Sampling+'}], [], [{**CC0, 'licence': ''}]):
            with tempfile.TemporaryDirectory() as t:
                fake_pack(Path(t) / 'packs', 'bad_pack', ['perc_x_01.flac'], credits=credits)
                with self.assertRaises(SystemExit, msg=repr(credits)):
                    build_index.build(Path(t) / 'packs', Path(t) / 'dist')

    def test_an_empty_library_pack_is_left_out_not_fatal(self):
        # library_pack.py leaves sounds: [] and credits: [] when nothing was kept: set aside, as before.
        with tempfile.TemporaryDirectory() as t:
            fake_pack(Path(t) / 'packs', 'ok_pack', ['perc_shaker_01.flac'], credits=[CC0])
            fake_pack(Path(t) / 'packs', 'vide', [], credits=[])
            build_index.build(Path(t) / 'packs', Path(t) / 'dist')
            ids = [e['id'] for e in json.loads((Path(t) / 'dist' / 'index.json').read_text())['packs']]
            self.assertEqual(['ok_pack'], ids)

    def test_a_catalogue_pack_without_credits_is_refused(self):
        # Only the model's packs (styles.json) may come without credits.
        with tempfile.TemporaryDirectory() as t:
            fake_pack(Path(t) / 'packs', 'percussions_acoustiques', ['perc_shaker_01.flac'])
            with self.assertRaises(SystemExit):
                build_index.build(Path(t) / 'packs', Path(t) / 'dist')

    def test_cc_by_2_5_is_accepted(self):
        self.assertTrue(build_index.licence_ok('CC-BY-2.5'))

    def test_build_passes_whitelisted_and_generated_packs(self):
        with tempfile.TemporaryDirectory() as t:
            fake_pack(Path(t) / 'packs', 'lib_pack', ['perc_shaker_01.flac'], credits=[CC0, {**CC0, 'licence': 'CC-BY-4.0'}])
            fake_pack(Path(t) / 'packs', 'trap', ['kick_01.flac'])  # generated by the model: no credits key
            build_index.build(Path(t) / 'packs', Path(t) / 'dist')
            ids = [e['id'] for e in json.loads((Path(t) / 'dist' / 'index.json').read_text())['packs']]
            self.assertEqual(['lib_pack', 'trap'], ids)


if __name__ == '__main__':
    unittest.main()
